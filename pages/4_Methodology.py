st.markdown(f"""
**Data flow in words.** The question passes three deterministic checks before a
token reaches the model, so the common attacks cost nothing to block. It is then
classified by a dedicated guard call whose only job is classification — it never
answers, so a successful manipulation of it yields no useful output. The
classifier's response must satisfy a key schema; a malformed response is treated
as a refusal.

Retrieval runs BM25 Okapi over {len(PASSAGES)} curated passages, implemented in
about thirty lines with no external dependency — chosen over an embedding store
because the corpus is small, the vocabulary is domain-specific and largely
literal, and a lighter dependency tree is one fewer thing to fail on deployment.
A relevance floor means an off-topic question that slipped past the guard
retrieves nothing, and the answering prompt is instructed to decline when handed
no passages.

The answering call receives the passages, the user's session profile if one
exists, and the question wrapped in delimiters that frame it as data. Output is
scanned for prompt leakage before display. A third call proposes follow-up
questions, which are rendered as buttons that feed back into the same pipeline —
they are not trusted shortcuts and are screened identically.
""")

