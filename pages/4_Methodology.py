st.markdown("""
**Prompt engineering.** Each of the five model calls has a narrow, single-purpose
system prompt with an explicit output contract. The two structured calls specify
their JSON keys exactly and are validated on return. Temperature is set by task:
zero for the guard classifier where determinism matters, 0.1 for the structured
assessment, 0.4 for the narrative where some variation is desirable, 0.5 for
follow-up generation. Every prompt that touches user text states that the
delimited span is data rather than instruction, and both answering prompts
carry an explicit instruction not to give financial advice — which is what keeps
the application on the right side of the disclaimer rather than merely
displaying it.

**Caching and cost.** Transaction queries are cached for six hours, so repeated
assessments of the same town and flat type cost one API call, not many. The
deterministic engines run on every rerun at negligible cost, which is why the
price slider can recompute the entire cost stack instantly without touching a
model.

**Graceful degradation.** If data.gov.sg is unavailable, the grant and
affordability results still render with a notice. If no API key is configured,
the whole of Use Case 1 except the written briefing still works. The application
is designed so that the parts a user most needs to trust are the parts least
able to fail.
""")
