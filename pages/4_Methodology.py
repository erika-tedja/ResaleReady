st.markdown("""
**Data flow in words.** The form yields a `Profile` object. That drives two
independent branches: the grant rules engine, which walks the published EHG
income tiers, the Family Grant flat-type table and the PHG proximity table,
attaching a reason string to every verdict; and a live query to data.gov.sg for
transactions matching the chosen towns and flat type over the last twelve
months. The two branches converge in the affordability engine, which derives
the loan ceiling from the servicing ratio, applies the 75% loan-to-value cap,
and works out the cash actually required after grants and CPF.

Those results are serialised into a verified-figures JSON block. **LLM Call A**
receives it and returns a structured assessment — a verdict, ranked risks,
prioritised actions. That response is validated against a required key schema;
an invalid response fails closed rather than degrading to prose. **LLM Call B**
then receives *both* the original figures and Call A's structured output, and
writes the narrative. The chain is real: Call B is not merely a second prompt,
it consumes Call A's output as its primary input and cannot run without it.
""")

